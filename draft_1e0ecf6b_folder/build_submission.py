def table(headers,rows,widths=None):
    widths=widths or [int(1020/len(headers))]*len(headers)
    out='<table><colgroup>'+''.join(f'<col width="{w}"/>' for w in widths)+'</colgroup><thead><tr>'
    out+=''.join('<th background-color="light-gray" vertical-align="top"><p>'+e(c)+'</p></th>' for c in headers)
    out+='</tr></thead><tbody>'
    for row in rows:
        assert len(row)==len(headers),(headers,row)
        out+='<tr>'+''.join('<td vertical-align="top"><p>'+e(c)+'</p></td>' for c in row)+'</tr>'
    parts.append(out+'</tbody></table>')
